//! Compatibility report serialization and executable output contracts.
#![cfg(feature = "evaluation")]

/// Report tests assert structured cells and shipped CLI/library output equality.
#[cfg(test)]
#[expect(
    clippy::missing_errors_doc,
    clippy::missing_panics_doc,
    reason = "test code is not rendered API documentation"
)]
#[expect(clippy::panic_in_result_fn, reason = "a test fails by panicking")]
mod tests {
    use core::error::Error;
    use std::process::Command;

    use rskrb5_ng::evaluation::{
        data::{ASSESSMENTS, Candidate, DerType, REPORTS, Support, V8_CONTRACT},
        render_markdown,
    };

    /// CLI stdout is byte-identical to the report generated by the library.
    #[test]
    fn executable_emits_library_report() -> Result<(), Box<dyn Error>> {
        let output = Command::new(env!("CARGO_BIN_EXE_rskrb5-ng-compat-report")).output()?;
        assert!(output.status.success());
        assert_eq!(
            String::from_utf8(output.stdout)?.replace("\r\n", "\n"),
            render_markdown().replace("\r\n", "\n")
        );
        Ok(())
    }

    /// Decision rows serialize each candidate's keyed support in contract-column order.
    #[test]
    fn report_serializes_decision_matrix_cells() -> Result<(), Box<dyn Error>> {
        let report = render_markdown();
        let decision_rows: Vec<_> = report
            .lines()
            .filter(|line| {
                line.starts_with("| rasn-kerberos |") || line.starts_with("| picky-krb |")
            })
            .collect();
        for assessment in ASSESSMENTS.iter().take(2) {
            let cells: Vec<_> = decision_rows
                .iter()
                .find(|line| line.contains(assessment.candidate.name()))
                .map(|line| line.trim_matches('|').split('|').map(str::trim).collect())
                .ok_or("decision row")?;
            assert_eq!(cells.first().copied(), Some(assessment.candidate.name()));
            let expected: Vec<_> = V8_CONTRACT
                .iter()
                .map(|area| assessment.support_for(area.id).to_string())
                .collect();
            assert_eq!(cells.get(1..).unwrap_or_default(), expected);
        }
        Ok(())
    }

    /// Candidate detail tables deliver the complete stored capability rows.
    #[test]
    fn report_serializes_candidate_detail_cells() -> Result<(), Box<dyn Error>> {
        let report = render_markdown();
        for candidate in REPORTS {
            let section = report
                .split("\n## ")
                .find(|section| section.starts_with(&format!("{}\n", candidate.candidate.name())))
                .ok_or("candidate section")?;
            for capability in candidate.capabilities {
                let expected = format!(
                    "| {} | {} | {} |",
                    capability.area, capability.support, capability.note
                );
                assert!(
                    section.lines().any(|line| line == expected),
                    "capability row missing for {}",
                    candidate.candidate.name()
                );
            }
            assert!(
                section
                    .lines()
                    .any(|line| line == format!("- License: `{}`", candidate.candidate.license()))
            );
        }
        Ok(())
    }

    /// Public report labels retain the candidate, license and ASN.1 identities they serialize.
    #[test]
    fn report_labels_identify_candidate_license_and_wire_type() {
        assert_eq!(Candidate::RasnKerberos.name(), "rasn-kerberos");
        assert_eq!(Candidate::KerbeirosFamily.license(), "AGPL-3.0");
        assert_eq!(DerType::ApRep.name(), "AP-REP");
        assert_eq!(Support::Partial.to_string(), "partial");
    }

    /// Support lookup selects matching keys and supplies No only for absent keys.
    #[test]
    fn support_lookup_distinguishes_matching_and_absent_areas() -> Result<(), Box<dyn Error>> {
        let assessment = ASSESSMENTS
            .iter()
            .find(|entry| entry.candidate == Candidate::RasnKerberos)
            .ok_or("assessment")?;
        assert_eq!(assessment.support_for("asn1"), Support::Partial);
        assert_eq!(assessment.support_for("missing-area"), Support::No);
        Ok(())
    }
}
