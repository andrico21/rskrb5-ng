# shellcheck shell=bash
# Host side of the MIT krb5 1.22.2 fixture `mit-kdc` (lane 1C), sourced by
# scripts/interop/run.sh. See the layout contract in scripts/interop/lib.sh.
#
# Container rskrb5-interop-mit-kdc (hostname kdc.test.rskrb5, network alias
# kdc.test.rskrb5 on rskrb5-interop): krb5kdc and kadmind of realm
# TEST.RSKRB5. Tmpfs mounts hold the KDC database, its stash, the secrets and
# the exported keytabs. Published on 127.0.0.1 (TCP and UDP for 88 and 464):
#   INTEROP_MIT_KDC_PORT (default 18088) -> 88, INTEROP_MIT_KPASSWD_PORT
#   (18464) -> 464, INTEROP_MIT_KADMIN_PORT (18749) -> 749.
# No extra capability and no --privileged.
#
# Lane 1D-a (advanced preauthentication) extends the same container: FAST,
# SPAKE, OTP (backed by the `radius` fixture, scripts/interop/radius/), PKINIT
# with a per-run test CA and anonymous Kerberos. Each mechanism is PROVEN by a
# self-check at the end of fixture_mit_kdc_up (and, for OTP, of
# fixture_radius_up, which needs both containers): the MIT client tools run
# inside the container with KRB5_TRACE and the assertions are on the mechanism
# lines of the trace and of the KDC log (scripts/interop/mit/preauth/selfcheck/).
# The env keys of lane 1D-a are recorded by interop_mit_preauth_env below.

interop_fixture mit-kdc
interop_suite mit interop_mit mit-kdc

# Per-run secrets of lane 1D-a (generated by interop_mit_preauth_secrets, delivered
# to the container's tmpfs with the base secrets; the radius fixture reuses the
# last two, so mit-kdc must be started before it, which path order guarantees).
INTEROP_MIT_PREAUTH_SECRET_NAMES=(
  INTEROP_MIT_FAST_USER_PASSWORD INTEROP_MIT_SPAKE_USER_PASSWORD
  INTEROP_RADIUS_SHARED_SECRET INTEROP_MIT_OTP_TOKEN
)
# Files copied out of /run/interop/out/pki into $INTEROP_STATE_DIR/mit/pki.
INTEROP_MIT_PKI_FILES=(ca-ec.pem ca-rsa.pem anchors.pem pkinit-ec.pem pkinit-ec.key pkinit-rsa.pem pkinit-rsa.key)

interop_mit_preauth_secrets() {
  local name
  for name in "${INTEROP_MIT_PREAUTH_SECRET_NAMES[@]}"; do
    interop_env "$name" "$(interop_new_secret)" || return 1
  done
}

# interop_mit_preauth_env OUT: the env keys of lane 1D-a (OUT is the mit
# state directory holding pki/). Principals and services are names, files are
# mode-0600 paths, the passwords and the OTP token are secrets (recorded by
# interop_mit_preauth_secrets). INTEROP_MIT_USER, INTEROP_MIT_USER_KEYTAB and
# INTEROP_MIT_KINIT_CCACHE (a testuser1 TGT) serve as the FAST armor source.
interop_mit_preauth_env() {
  local pki="$1/pki"
  interop_env INTEROP_MIT_FAST_USER fastuser
  interop_env INTEROP_MIT_FAST_REQUIRED_SERVICE fastrequired/svc.test.rskrb5
  interop_env INTEROP_MIT_FAST_INDICATOR fast-ec
  interop_env INTEROP_MIT_SPAKE_USER spakeuser
  interop_env INTEROP_MIT_SPAKE_REQUIRED_SERVICE spakerequired/svc.test.rskrb5
  interop_env INTEROP_MIT_SPAKE_INDICATOR spake
  interop_env INTEROP_MIT_SPAKE_GROUPS "edwards25519 P-256 P-384 P-521"
  interop_env INTEROP_MIT_OTP_USER otpuser
  interop_env INTEROP_MIT_OTP_REQUIRED_SERVICE otprequired/svc.test.rskrb5
  interop_env INTEROP_MIT_OTP_INDICATOR otp
  interop_env INTEROP_MIT_PKINIT_USER pkinituser
  interop_env INTEROP_MIT_PKINIT_CERT "$pki/pkinit-ec.pem"
  interop_env INTEROP_MIT_PKINIT_KEY "$pki/pkinit-ec.key"
  interop_env INTEROP_MIT_PKINIT_RSA_USER pkinitrsa
  interop_env INTEROP_MIT_PKINIT_RSA_CERT "$pki/pkinit-rsa.pem"
  interop_env INTEROP_MIT_PKINIT_RSA_KEY "$pki/pkinit-rsa.key"
  interop_env INTEROP_MIT_PKINIT_CA "$pki/ca-ec.pem"
  interop_env INTEROP_MIT_PKINIT_RSA_CA "$pki/ca-rsa.pem"
  interop_env INTEROP_MIT_PKINIT_ANCHORS "$pki/anchors.pem"
  interop_env INTEROP_MIT_PKINIT_KDC_PRINCIPAL krbtgt/TEST.RSKRB5
  interop_env INTEROP_MIT_PKINIT_REQUIRED_SERVICE pkinitrequired/svc.test.rskrb5
  interop_env INTEROP_MIT_PKINIT_INDICATOR pkinit
  interop_env INTEROP_MIT_ANONYMOUS_PRINCIPAL WELLKNOWN/ANONYMOUS
  interop_env INTEROP_MIT_ANONYMOUS_REALM WELLKNOWN:ANONYMOUS
}

# interop_mit_run_selfcheck CONTAINER CHECK...: runs the container-side checks
# (scripts/interop/mit/preauth/selfcheck/CHECK.sh) and fails naming the fixture.
interop_mit_run_selfcheck() {
  local container="$1" check
  shift
  for check in "$@"; do
    interop_log "fixture mit-kdc: self-check $check"
    interop_rt exec "$container" bash "/opt/interop/mit/preauth/selfcheck/$check.sh" >&2 ||
      interop_die "fixture mit-kdc (container $container): self-check $check failed" || return 1
  done
}

fixture_mit_kdc_up() {
  local fixture=mit-kdc container image dir out
  container="$(interop_container_name "$fixture")"
  local host=127.0.0.1
  local kdc_port="${INTEROP_MIT_KDC_PORT:-18088}"
  local kpasswd_port="${INTEROP_MIT_KPASSWD_PORT:-18464}"
  local kadmin_port="${INTEROP_MIT_KADMIN_PORT:-18749}"
  dir="$INTEROP_ROOT/scripts/interop/mit"
  out="$INTEROP_STATE_DIR/mit"

  image="$(interop_build_image mit "$dir")" || return 1
  interop_env INTEROP_MIT_IMAGE "$image"
  interop_env INTEROP_MIT_USER_PASSWORD "$(interop_new_secret)"
  interop_env INTEROP_MIT_PREAUTH_USER_PASSWORD "$(interop_new_secret)"
  interop_env INTEROP_MIT_KPASSWD_USER_PASSWORD "$(interop_new_secret)"
  interop_env INTEROP_MIT_KPASSWD_USER_NEW_PASSWORD "$(interop_new_secret)"
  interop_env INTEROP_MIT_ADMIN_PASSWORD "$(interop_new_secret)"
  interop_mit_preauth_secrets || return 1

  interop_run_container "$fixture" "$image" \
    --hostname kdc.test.rskrb5 --network-alias kdc.test.rskrb5 \
    --tmpfs /var/lib/krb5kdc:rw,mode=0700 \
    -p "$host:$kdc_port:88/tcp" -p "$host:$kdc_port:88/udp" \
    -p "$host:$kpasswd_port:464/tcp" -p "$host:$kpasswd_port:464/udp" \
    -p "$host:$kadmin_port:749/tcp" || interop_die "fixture $fixture: container $container did not start" || return 1
  interop_deliver_secrets "$container" INTEROP_MIT_USER_PASSWORD INTEROP_MIT_PREAUTH_USER_PASSWORD \
    INTEROP_MIT_KPASSWD_USER_PASSWORD INTEROP_MIT_ADMIN_PASSWORD \
    "${INTEROP_MIT_PREAUTH_SECRET_NAMES[@]}" || return 1
  interop_wait_ready "$fixture" || return 1
  interop_wait_tcp "$fixture" "$host" "$kdc_port" || return 1
  interop_wait_tcp "$fixture" "$host" "$kpasswd_port" || return 1
  interop_wait_tcp "$fixture" "$host" "$kadmin_port" || return 1

  interop_prepare_private_dir "$out" || return 1
  local file
  for file in http.keytab host.keytab testuser1.keytab preauthuser.keytab kinit.ccache; do
    interop_copy_out "$container" "/run/interop/out/$file" "$out/$file" || return 1
  done
  interop_prepare_private_dir "$out/pki" || return 1
  for file in "${INTEROP_MIT_PKI_FILES[@]}"; do
    interop_copy_out "$container" "/run/interop/out/pki/$file" "$out/pki/$file" || return 1
  done

  interop_env INTEROP_MIT_CONTAINER "$container"
  interop_env INTEROP_MIT_REALM TEST.RSKRB5
  interop_env INTEROP_MIT_KDC "$host:$kdc_port"
  interop_env INTEROP_MIT_KPASSWD "$host:$kpasswd_port"
  interop_env INTEROP_MIT_KADMIN "$host:$kadmin_port"
  interop_env INTEROP_MIT_USER testuser1
  interop_env INTEROP_MIT_USER_KEYTAB "$out/testuser1.keytab"
  interop_env INTEROP_MIT_PREAUTH_USER preauthuser
  interop_env INTEROP_MIT_PREAUTH_USER_KEYTAB "$out/preauthuser.keytab"
  interop_env INTEROP_MIT_KPASSWD_USER kpasswduser
  interop_env INTEROP_MIT_HTTP_SERVICE HTTP/http.test.rskrb5
  interop_env INTEROP_MIT_HTTP_KEYTAB "$out/http.keytab"
  interop_env INTEROP_MIT_HOST_SERVICE host/mit-kdc.test.rskrb5
  interop_env INTEROP_MIT_HOST_KEYTAB "$out/host.keytab"
  interop_env INTEROP_MIT_KINIT_CCACHE "FILE:$out/kinit.ccache"
  interop_env INTEROP_MIT_ADMIN_PRINCIPAL admin/admin
  interop_env INTEROP_MIT_DISPOSABLE_PRINCIPALS "kadm5test1 kadm5test2"
  interop_mit_preauth_env "$out"
  interop_mit_run_selfcheck "$container" 20-fast 30-spake 45-pkinit 48-anonymous || return 1
}

fixture_mit_kdc_logs() {
  local dir="$1" container file
  container="$(interop_container_name mit-kdc)"
  for file in krb5kdc.log kadmind.log krb5lib.log; do
    interop_rt exec "$container" cat "/var/log/krb5/$file" >"$dir/mit-kdc-$file" 2>/dev/null || true
  done
}
