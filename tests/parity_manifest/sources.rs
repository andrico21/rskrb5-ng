//! Lexical scans of the checkout that back the manifest's claims; every scan fails closed.

extern crate alloc;

use alloc::collections::BTreeSet;
use std::{fs, path::Path};

use toml::{Table, Value};

use crate::{TestError, model::read};

/// Test attributes this repository uses.
const TEST_ATTRIBUTES: [&str; 2] = ["#[test]", "#[tokio::test"];
/// Declaration keywords a public Rust symbol may follow.
const DECLARATIONS: [&str; 8] = [
    "pub fn ",
    "pub async fn ",
    "pub const fn ",
    "pub struct ",
    "pub enum ",
    "pub type ",
    "pub trait ",
    "pub mod ",
];

/// Every `.rs` file below `relative`, as repository-relative text with LF endings.
pub(crate) fn rust_sources(relative: &str) -> Result<Vec<(String, String)>, TestError> {
    let mut found = Vec::new();
    let mut pending = vec![relative.to_owned()];
    while let Some(directory) = pending.pop() {
        let absolute = Path::new(env!("CARGO_MANIFEST_DIR")).join(&directory);
        for entry in fs::read_dir(absolute)? {
            let file_name = entry?.file_name();
            let name = file_name
                .into_string()
                .map_err(|raw| format!("non-UTF-8 name {raw:?}"))?;
            let child = format!("{directory}/{name}");
            if Path::new(env!("CARGO_MANIFEST_DIR")).join(&child).is_dir() {
                pending.push(child);
                continue;
            }
            if has_extension(&name, "rs") {
                let source = read(&child)?;
                found.push((child, source));
            }
        }
    }
    assert!(!found.is_empty(), "no Rust sources below {relative}");
    Ok(found)
}

/// Whether `path` has the extension `wanted`, ignoring ASCII case.
fn has_extension(path: &str, wanted: &str) -> bool {
    Path::new(path)
        .extension()
        .is_some_and(|extension| extension.eq_ignore_ascii_case(wanted))
}

/// Whether `source` defines test `function`, written out or generated by a local test macro.
fn defines_test(source: &str, function: &str) -> bool {
    let lines: Vec<&str> = source.lines().map(str::trim).collect();
    let header = format!("fn {function}(");
    let written = lines.iter().enumerate().any(|(index, line)| {
        let is_header = line.starts_with(&header) || line.starts_with(&format!("async {header}"));
        let attributes = lines
            .iter()
            .take(index)
            .rev()
            .take_while(|previous| !previous.ends_with('}') && !previous.ends_with(';'));
        is_header
            && attributes
                .take(12)
                .any(|previous| starts_with_any(previous, &TEST_ATTRIBUTES))
    });
    let generated = source.contains("macro_rules!")
        && source.contains("fn $name(")
        && lines
            .iter()
            .any(|line| starts_with_any(line, &TEST_ATTRIBUTES))
        && lines
            .iter()
            .any(|line| line.starts_with(&format!("{function},")));
    written || generated
}

/// Whether `line` starts with one of `prefixes`.
fn starts_with_any(line: &str, prefixes: &[&str]) -> bool {
    prefixes.iter().any(|prefix| line.starts_with(prefix))
}

/// Checks a `tests/...rs::function` or `src/...rs::function` test name against the checkout.
pub(crate) fn check_test_name(name: &str) -> Result<(), TestError> {
    let (file, function) = name
        .rsplit_once("::")
        .ok_or_else(|| format!("{name}: not path::function"))?;
    let rooted = file.starts_with("tests/") || file.starts_with("src/");
    assert!(
        rooted && has_extension(file, "rs") && !file.contains(".."),
        "{name}: bad path"
    );
    let identifier = function
        .bytes()
        .all(|byte| byte == b'_' || byte.is_ascii_alphanumeric());
    assert!(
        identifier && !function.is_empty(),
        "{name}: bad function name"
    );
    assert!(
        defines_test(&read(file)?, function),
        "{name}: no such test function"
    );
    Ok(())
}

/// Whether the final path segment of `symbol` is declared publicly in `sources`.
#[test]
fn symbol_evidence_requires_full_owner_path() {
    let sources = vec![(
        "src/keytab.rs".to_owned(),
        "pub struct Principal;\nimpl Principal {\n pub fn from_name() {}\n}\npub struct Keytab;"
            .to_owned(),
    )];
    assert!(declares(&sources, "keytab::Principal::from_name"));
    assert!(!declares(&sources, "keytab::Keytab::from_name"));
    assert!(!declares(&sources, "ccache::Principal::from_name"));
}

/// Resolve the module and enclosing impl or enum, not an unrelated same-named item.
fn resolve_alias(sources: &[(String, String)], symbol: &str) -> String {
    let mut resolved = symbol.to_owned();
    for _ in 0_u8..8 {
        let mut replacement = None;
        for (file, source) in sources {
            let module = file
                .trim_start_matches("src/")
                .trim_end_matches(".rs")
                .replace('/', "::");
            for line in source.lines().map(str::trim) {
                if let Some((alias, target)) = line
                    .strip_prefix("pub type ")
                    .and_then(|rest| rest.split_once(" = "))
                {
                    let prefix = format!("{module}::{alias}");
                    if let Some(suffix) = resolved
                        .strip_prefix(&prefix)
                        .filter(|suffix| suffix.is_empty() || suffix.starts_with("::"))
                    {
                        let destination = target.trim_end_matches(';');
                        let path = destination
                            .strip_prefix("crate::")
                            .map_or_else(|| format!("{module}::{destination}"), str::to_owned);
                        replacement = Some(format!("{path}{suffix}"));
                    }
                }
            }
        }
        if let Some(path) = replacement {
            if path == resolved {
                break;
            }
            resolved = path;
        } else {
            break;
        }
    }
    resolved
}

/// Match a qualified public symbol against its module and owning type.
pub(crate) fn declares(sources: &[(String, String)], symbol: &str) -> bool {
    let resolved = resolve_alias(sources, symbol);
    let segments: Vec<&str> = resolved.split("::").collect();
    let Some((item, parents)) = segments.split_last() else {
        return false;
    };
    sources.iter().any(|(file, source)| {
        let module = file
            .strip_prefix("src/")
            .unwrap_or(file)
            .trim_end_matches(".rs")
            .replace('/', "::");
        let included = sources.iter().find(|(_, parent)| {
            parent.contains(&format!(
                "include!(\"{}\")",
                file.trim_start_matches("src/")
            ))
        });
        let effective_module = included.map_or(module, |(parent, _)| {
            parent
                .trim_start_matches("src/")
                .trim_end_matches(".rs")
                .replace('/', "::")
        });
        let module_name = path_module(sources, file).unwrap_or(effective_module);
        let mut depth = 0_usize;
        let mut owner: Option<(String, usize)> = None;
        for line in source.lines().map(str::trim) {
            if line.starts_with("//") {
                continue;
            }
            if let Some(header) = line.strip_prefix("impl") {
                let plain = header.trim_start();
                let after_generics = if plain.starts_with('<') {
                    plain.split_once('>').map_or(plain, |(_, rest)| rest.trim())
                } else {
                    plain
                };
                let target = after_generics
                    .split_once(" for ")
                    .map_or(after_generics, |(_, target)| target);
                let name: String = target
                    .chars()
                    .take_while(|character| character.is_alphanumeric() || *character == '_')
                    .collect();
                owner = Some((name, depth));
            } else if let Some(header) = line.strip_prefix("pub enum ") {
                owner = Some((identifier(header), depth));
            } else {
                // Other lines retain their enclosing owner until its closing brace.
            }
            for keyword in DECLARATIONS {
                if let Some(rest) = line.strip_prefix(keyword) {
                    let name = identifier(rest);
                    if name == *item {
                        let method = keyword.contains("fn ");
                        let expected = parents.join("::");
                        if method {
                            if let Some((ty, _)) = &owner {
                                if let Some((expected_module, expected_type)) =
                                    expected.rsplit_once("::")
                                    && expected_type == ty
                                    && (module_name == expected_module
                                        || module_name.starts_with(&format!("{expected_module}::")))
                                {
                                    return true;
                                }
                            } else if module_name == expected {
                                return true;
                            } else {
                                // The same item name in a different module is not evidence.
                            }
                        } else if module_name == expected {
                            return true;
                        } else {
                            // Type declarations must belong to the requested module.
                        }
                    }
                }
            }
            if let Some((ty, _)) = &owner
                && identifier(line) == *item
                && !line.starts_with("pub ")
                && let Some((expected_module, expected_type)) = parents.join("::").rsplit_once("::")
                && expected_type == ty
                && (module_name == expected_module
                    || module_name.starts_with(&format!("{expected_module}::")))
            {
                return true;
            }
            depth = depth
                .saturating_add(line.matches('{').count())
                .saturating_sub(line.matches('}').count());
            if owner.as_ref().is_some_and(|(_, start)| depth <= *start) {
                owner = None;
            }
        }
        false
    })
}

/// First Rust identifier at a declaration boundary.
fn path_module(sources: &[(String, String)], file: &str) -> Option<String> {
    let marker = format!("#[path = \"{}\"]", file.trim_start_matches("src/"));
    sources.iter().find_map(|(parent_file, parent)| {
        if parent_file == "src/lib.rs" {
            return None;
        }
        let (_, rest) = parent.split_once(&marker)?;
        let declaration = rest
            .lines()
            .map(str::trim)
            .find_map(|line| line.strip_prefix("pub mod "))?;
        let parent_module = parent_file
            .trim_start_matches("src/")
            .trim_end_matches(".rs")
            .replace('/', "::");
        Some(format!("{parent_module}::{}", identifier(declaration)))
    })
}

/// First Rust identifier at a declaration boundary.
fn identifier(text: &str) -> String {
    text.chars()
        .take_while(|character| character.is_alphanumeric() || *character == '_')
        .collect()
}

/// Variants of `RejectedFeature`, read from `src/error.rs` and the files it includes.
pub(crate) fn rejected_feature_variants() -> Result<BTreeSet<String>, TestError> {
    let root = read("src/error.rs")?;
    let mut text = root.clone();
    for line in root.lines().map(str::trim) {
        if let Some(path) = line
            .strip_prefix("include!(\"")
            .and_then(|rest| rest.strip_suffix("\");"))
        {
            text.push_str(&read(&format!("src/{path}"))?);
        }
    }
    let (_, body) = text
        .split_once("pub enum RejectedFeature {")
        .ok_or("RejectedFeature not found")?;
    let mut variants = BTreeSet::new();
    let mut depth = 0_usize;
    for line in body.lines().map(str::trim) {
        if depth == 0 && line == "}" {
            return Ok(variants);
        }
        let name: String = line
            .chars()
            .take_while(char::is_ascii_alphanumeric)
            .collect();
        if depth == 0 && name.chars().next().is_some_and(char::is_uppercase) {
            let fresh = variants.insert(name);
            assert!(fresh, "duplicate RejectedFeature variant");
        }
        depth = depth
            .saturating_add(line.matches('{').count())
            .saturating_sub(line.matches('}').count());
    }
    Err("RejectedFeature body is not closed".into())
}

/// Whether `docs/<file>.md#<anchor>` names an existing explicit anchor.
pub(crate) fn anchor_exists(reference: &str) -> Result<bool, TestError> {
    let (file, anchor) = reference
        .split_once('#')
        .ok_or_else(|| format!("{reference}: no anchor"))?;
    let shaped = file.starts_with("docs/") && has_extension(file, "md") && !file.contains("..");
    assert!(
        shaped && !anchor.is_empty(),
        "{reference}: bad document reference"
    );
    let target = format!("<a id=\"{anchor}\"></a>");
    Ok(read(file)?.lines().any(|line| line.trim() == target))
}

/// Feature names declared in `Cargo.toml`.
pub(crate) fn cargo_features() -> Result<BTreeSet<String>, TestError> {
    let manifest: Table = read("Cargo.toml")?.parse()?;
    let features = manifest
        .get("features")
        .and_then(Value::as_table)
        .ok_or("features")?;
    Ok(features.keys().cloned().collect())
}
