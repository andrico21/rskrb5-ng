/// Test attributes this repository uses.
const TEST_ATTRIBUTES: [&str; 2] = ["#[test]", "#[tokio::test"];
/// Declaration keywords a public Rust symbol may follow.
const DECLARATIONS: [&str; 8] = [
    "pub fn ",
    "pub async fn ",
    "pub const fn ",
    "pub struct ",
    "pub enum ",
    "pub type ",
    "pub trait ",
    "pub mod ",
];

/// Every `.rs` file below `relative`, as repository-relative text with LF endings.
pub(crate) fn rust_sources(relative: &str) -> Result<Vec<(String, String)>, TestError> {
    let mut found = Vec::new();
    let mut pending = vec![relative.to_owned()];
    while let Some(directory) = pending.pop() {
        let absolute = Path::new(env!("CARGO_MANIFEST_DIR")).join(&directory);
        for entry in fs::read_dir(absolute)? {
            let file_name = entry?.file_name();
            let name = file_name
                .into_string()
                .map_err(|raw| format!("non-UTF-8 name {raw:?}"))?;
            let child = format!("{directory}/{name}");
            if Path::new(env!("CARGO_MANIFEST_DIR")).join(&child).is_dir() {
                pending.push(child);
                continue;
            }
            if has_extension(&name, "rs") {
                let source = read(&child)?;
                found.push((child, source));
            }
        }
    }
    assert!(!found.is_empty(), "no Rust sources below {relative}");
    Ok(found)
}

/// Whether `path` has the extension `wanted`, ignoring ASCII case.
fn has_extension(path: &str, wanted: &str) -> bool {
    Path::new(path)
        .extension()
        .is_some_and(|extension| extension.eq_ignore_ascii_case(wanted))
}

/// Whether `source` defines test `function`, written out or generated by a local test macro.
fn defines_test(source: &str, function: &str) -> bool {
    let lines: Vec<&str> = source.lines().map(str::trim).collect();
    let header = format!("fn {function}(");
    let written = lines.iter().enumerate().any(|(index, line)| {
        let is_header = line.starts_with(&header) || line.starts_with(&format!("async {header}"));
        let attributes = lines
            .iter()
            .take(index)
            .rev()
            .take_while(|previous| !previous.ends_with('}') && !previous.ends_with(';'));
        is_header
            && attributes
                .take(12)
                .any(|previous| starts_with_any(previous, &TEST_ATTRIBUTES))
    });
    let generated = source.contains("macro_rules!")
        && source.contains("fn $name(")
        && lines
            .iter()
            .any(|line| starts_with_any(line, &TEST_ATTRIBUTES))
        && lines
            .iter()
            .any(|line| line.starts_with(&format!("{function},")));
    written || generated
}

/// Whether `line` starts with one of `prefixes`.
fn starts_with_any(line: &str, prefixes: &[&str]) -> bool {
    prefixes.iter().any(|prefix| line.starts_with(prefix))
}

/// Checks a `tests/...rs::function` or `src/...rs::function` test name against the checkout.
pub(crate) fn check_test_name(name: &str) -> Result<(), TestError> {
    let (file, function) = name
        .rsplit_once("::")
        .ok_or_else(|| format!("{name}: not path::function"))?;
    let rooted = file.starts_with("tests/") || file.starts_with("src/");
    assert!(
        rooted && has_extension(file, "rs") && !file.contains(".."),
        "{name}: bad path"
    );
    let identifier = function
        .bytes()
        .all(|byte| byte == b'_' || byte.is_ascii_alphanumeric());
    assert!(
        identifier && !function.is_empty(),
        "{name}: bad function name"
    );
    assert!(
        defines_test(&read(file)?, function),
        "{name}: no such test function"
    );
    Ok(())
}

/// Same-named methods must not prove a different module or owning type.
#[test]
fn symbol_evidence_requires_full_owner_path() -> Result<(), TestError> {
    let sources = vec![(
        "src/keytab.rs".to_owned(),
        "pub struct Principal;\nimpl Principal {\n pub fn from_name() {}\n}\npub struct Keytab;"
            .to_owned(),
    )];
    let cleaned = sanitized_sources(&sources)?;
    assert!(declares_clean(
        &cleaned,
        &sources,
        "keytab::Principal::from_name"
    ));
    assert!(!declares(&sources, "keytab::Keytab::from_name"));
    assert!(!declares(&sources, "ccache::Principal::from_name"));
    let child = vec![(
        "src/keytab/child.rs".to_owned(),
        "pub struct Keytab;\nimpl Keytab {\n pub fn from_name() {}\n}".to_owned(),
    )];
    assert!(!declares(&child, "keytab::Keytab::from_name"));
    assert!(!declares(
        &[sources, child].concat(),
        "keytab::Keytab::from_name"
    ));
    let ghost = vec![(
        "src/keytab.rs".to_owned(),
        "/*\npub struct Ghost;\n*/".to_owned(),
    )];
    assert!(!declares(&ghost, "keytab::Ghost"));
    for visibility in ["mod", "pub mod", "pub(crate) mod", "mod\n", "mod\t"] {
        let nested = vec![(
            "src/keytab.rs".to_owned(),
            format!(
                "{visibility} hidden {{\npub struct Ghost;\nimpl Ghost {{\npub fn new() {{}}\n}}\npub type Alias = Ghost;\n}}\npub struct Real;"
            ),
        )];
        for symbol in [
            "keytab::Ghost",
            "keytab::Ghost::new",
            "keytab::Alias",
            "keytab::hidden::Ghost",
        ] {
            assert!(
                !declares(&nested, symbol),
                "unsupported inline scope admitted {symbol}"
            );
        }
        assert!(declares(&nested, "keytab::Real"));
    }
    let real = vec![
        ("src/keytab.rs".to_owned(), "pub struct Keytab;".to_owned()),
        (
            "src/keytab/child.rs".to_owned(),
            "impl super::Keytab {\n pub fn from_name() {}\n}".to_owned(),
        ),
    ];
    assert!(declares(&real, "keytab::Keytab::from_name"));
    Ok(())
}

/// Resolve the module and enclosing impl or enum, not an unrelated same-named item.
fn resolve_alias(sources: &[(String, String)], symbol: &str) -> String {
    let mut resolved = symbol.to_owned();
    for _ in 0_u8..8 {
        let mut replacement = None;
        for (file, source) in sources {
            let module = file
                .trim_start_matches("src/")
                .trim_end_matches(".rs")
                .replace('/', "::");
            for line in source.lines().map(str::trim) {
                if let Some((alias, target)) = line
                    .strip_prefix("pub type ")
                    .and_then(|rest| rest.split_once(" = "))
                {
                    let prefix = format!("{module}::{alias}");
                    if let Some(suffix) = resolved
                        .strip_prefix(&prefix)
                        .filter(|suffix| suffix.is_empty() || suffix.starts_with("::"))
                    {
                        let destination = target.trim_end_matches(';');
                        let path = destination
                            .strip_prefix("crate::")
                            .map_or_else(|| format!("{module}::{destination}"), str::to_owned);
                        replacement = Some(format!("{path}{suffix}"));
                    }
                }
            }
        }
        if let Some(path) = replacement {
            if path == resolved {
                break;
            }
            resolved = path;
        } else {
            break;
        }
    }
    resolved
}

/// Match a qualified public symbol against its module and owning type.
pub(crate) fn declares(sources: &[(String, String)], symbol: &str) -> bool {
    let clean = sanitized_sources(sources);
    clean.is_ok_and(|cleaned| declares_clean(&cleaned, sources, symbol))
}

/// Reuse the gate lexer so nested comments and literal contents cannot become declarations.
///
/// Paths and texts cross the pipe as NUL-terminated UTF-8 fields, so every feature closure
/// builds this without the optional `serde_json` dependency.
pub(crate) fn sanitized_sources(
    sources: &[(String, String)],
) -> Result<Vec<(String, String)>, TestError> {
    let mut input = String::new();
    for (path, text) in sources {
        if path.contains('\0') || text.contains('\0') {
            return Err(format!("{path}: NUL cannot cross the lexer pipe").into());
        }
        input.push_str(path);
        input.push('\0');
        input.push_str(text);
        input.push('\0');
    }
    let mut child = Command::new("python3")
        .arg("scripts/lint-gates/parity_cfg.py")
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .env("PYTHONDONTWRITEBYTECODE", "1")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or("lexer stdin")?
        .write_all(input.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        return Err("Rust lexer failed".into());
    }
    let fields: Vec<&str> = str::from_utf8(&output.stdout)?
        .split_terminator('\0')
        .collect();
    if sources.len().checked_mul(2) != Some(fields.len()) {
        return Err("Rust lexer output lost a source".into());
    }
    let paths = fields.iter().step_by(2);
    let texts = fields.iter().skip(1).step_by(2);
    Ok(paths
        .zip(texts)
        .map(|(path, text)| ((*path).to_owned(), without_inline_modules(text)))
        .collect())
}

/// Inline modules are unsupported evidence scopes; erase their bodies before alias resolution.
fn without_inline_modules(source: &str) -> String {
    let mut result = String::new();
    let mut rest = source;
    while let Some(index) = rest.find("mod") {
        let (prefix, candidate) = rest.split_at(index);
        result.push_str(prefix);
        let boundary = candidate.chars().nth(3).is_some_and(char::is_whitespace)
            && prefix
                .chars()
                .next_back()
                .is_none_or(|ch| !ch.is_alphanumeric() && ch != '_');
        let delimiter = candidate.find(['{', ';']);
        if boundary
            && let Some(open) = delimiter
            && candidate
                .get(open..)
                .is_some_and(|tail| tail.starts_with('{'))
        {
            let mut depth = 0_usize;
            let mut end = candidate.len();
            for (position, character) in candidate
                .char_indices()
                .skip_while(|(position, _)| *position < open)
            {
                if character == '{' {
                    depth = depth.saturating_add(1);
                }
                if character == '}' {
                    depth = depth.saturating_sub(1);
                    if depth == 0 {
                        end = position.saturating_add(1);
                        break;
                    }
                }
            }
            let (removed, remaining) = candidate.split_at(end);
            result.extend(
                removed
                    .chars()
                    .map(|ch| if ch == '\n' { '\n' } else { ' ' }),
            );
            rest = remaining;
        } else {
            let (keyword, remaining) = candidate.split_at(3);
            result.push_str(keyword);
            rest = remaining;
        }
    }
    result.push_str(rest);
    result
}

/// Resolve declarations after lexical removal of comments and literals.
fn declares_clean(
    sources: &[(String, String)],
    originals: &[(String, String)],
    symbol: &str,
) -> bool {
    declares_in(sources, &scopes(sources, originals), symbol)
}

/// Facts of one source that do not depend on the symbol being looked up.
pub(crate) struct Scope {
    /// Module after `include!` and `#[path]` redirection.
    module: String,
    /// Trimmed lines declaring a struct, public or not.
    structs: Vec<String>,
    /// Trimmed names imported by `use super::` statements.
    imports: Vec<String>,
}

/// The [`Scope`] of each source, in source order.
///
/// It depends only on the checkout, so a caller checking many symbols computes it once.
pub(crate) fn scopes(sources: &[(String, String)], originals: &[(String, String)]) -> Vec<Scope> {
    sources
        .iter()
        .map(|(file, source)| {
            let module = file
                .strip_prefix("src/")
                .unwrap_or(file)
                .trim_end_matches(".rs")
                .replace('/', "::");
            let included = originals.iter().find(|(_, parent)| {
                parent.contains(&format!(
                    "include!(\"{}\")",
                    file.trim_start_matches("src/")
                ))
            });
            let effective_module = included.map_or(module, |(parent, _)| {
                parent
                    .trim_start_matches("src/")
                    .trim_end_matches(".rs")
                    .replace('/', "::")
            });
            let structs = source
                .lines()
                .map(str::trim)
                .filter(|line| line.starts_with("pub struct ") || line.starts_with("struct "))
                .map(str::to_owned)
                .collect();
            let imports = source
                .split(';')
                .filter_map(|statement| statement.trim().strip_prefix("use super::"))
                .flat_map(|imports| {
                    imports
                        .trim()
                        .trim_start_matches('{')
                        .trim_end_matches('}')
                        .split(',')
                        .map(|entry| entry.trim().to_owned())
                })
                .collect();
            Scope {
                module: path_module(originals, file).unwrap_or(effective_module),
                structs,
                imports,
            }
        })
        .collect()
}

/// [`declares_clean`] with the [`Scope`] of each source already resolved.
pub(crate) fn declares_in(sources: &[(String, String)], scopes: &[Scope], symbol: &str) -> bool {
    let resolved = resolve_alias(sources, symbol);
    let segments: Vec<&str> = resolved.split("::").collect();
    let Some((item, parents)) = segments.split_last() else {
        return false;
    };
    sources.iter().zip(scopes).any(|((_, source), scope)| {
        let module_name = &scope.module;
        let mut depth = 0_usize;
        let mut owner: Option<(String, usize)> = None;
        for line in source.lines().map(str::trim) {
            if line.starts_with("//") {
                continue;
            }
            if let Some(header) = line.strip_prefix("impl") {
                let plain = header.trim_start();
                let after_generics = if plain.starts_with('<') {
                    plain.split_once('>').map_or(plain, |(_, rest)| rest.trim())
                } else {
                    plain
                };
                let target = after_generics
                    .split_once(" for ")
                    .map_or(after_generics, |(_, target)| target);
                let name: String = target
                    .chars()
                    .take_while(|character| {
                        character.is_alphanumeric() || matches!(character, '_' | ':')
                    })
                    .collect();
                let qualified = impl_owner(scope, &name);
                owner = Some((qualified, depth));
            } else if let Some(header) = line.strip_prefix("pub enum ") {
                owner = Some((format!("{module_name}::{}", identifier(header)), depth));
            } else {
                // Other lines retain their enclosing owner until its closing brace.
            }
            for keyword in DECLARATIONS {
                if let Some(rest) = line.strip_prefix(keyword) {
                    let name = identifier(rest);
                    if name == *item {
                        let method = keyword.contains("fn ");
                        let expected = parents.join("::");
                        if method {
                            if let Some((ty, _)) = &owner {
                                if expected == *ty && declares_in(sources, scopes, &expected) {
                                    return true;
                                }
                            } else if *module_name == expected {
                                return true;
                            } else {
                                // The same item name in a different module is not evidence.
                            }
                        } else if *module_name == expected {
                            return true;
                        } else {
                            // Type declarations must belong to the requested module.
                        }
                    }
                }
            }
            if let Some((ty, _)) = &owner
                && identifier(line) == *item
                && !line.starts_with("pub ")
                && parents.join("::") == *ty
            {
                return true;
            }
            depth = depth
                .saturating_add(line.matches('{').count())
                .saturating_sub(line.matches('}').count());
            if owner.as_ref().is_some_and(|(_, start)| depth <= *start) {
                owner = None;
            }
        }
        false
    })
}

/// First Rust identifier at a declaration boundary.
fn path_module(sources: &[(String, String)], file: &str) -> Option<String> {
    let marker = format!("#[path = \"{}\"]", file.trim_start_matches("src/"));
    sources.iter().find_map(|(parent_file, parent)| {
        if parent_file == "src/lib.rs" {
            return None;
        }
        let (_, rest) = parent.split_once(&marker)?;
        let declaration = rest
            .lines()
            .map(str::trim)
            .find_map(|line| line.strip_prefix("pub mod "))?;
        let parent_module = parent_file
            .trim_start_matches("src/")
            .trim_end_matches(".rs")
            .replace('/', "::");
        Some(format!("{parent_module}::{}", identifier(declaration)))
    })
}

/// Resolve explicit parent paths and imported parent types without basename conflation.
fn impl_owner(scope: &Scope, name: &str) -> String {
    let module = &scope.module;
    let parent = module.rsplit_once("::").map_or("", |(prefix, _)| prefix);
    if let Some(path) = name.strip_prefix("super::") {
        return format!("{parent}::{path}");
    }
    if let Some(path) = name.strip_prefix("crate::") {
        return path.to_owned();
    }
    let public = format!("pub struct {name}");
    let private = format!("struct {name}");
    let local = scope
        .structs
        .iter()
        .any(|entry| entry.starts_with(&public) || entry.starts_with(&private));
    let imported = scope.imports.iter().any(|entry| entry == name);
    if imported && !local {
        format!("{parent}::{name}")
    } else {
        format!("{module}::{name}")
    }
}

/// First Rust identifier at a declaration boundary.
fn identifier(text: &str) -> String {
    text.chars()
        .take_while(|character| character.is_alphanumeric() || *character == '_')
        .collect()
}

/// Variants of `RejectedFeature`, read from `src/error.rs` and the files it includes.
pub(crate) fn rejected_feature_variants() -> Result<BTreeSet<String>, TestError> {
    let root = read("src/error.rs")?;
    let mut text = root.clone();
    for line in root.lines().map(str::trim) {
        if let Some(path) = line
            .strip_prefix("include!(\"")
            .and_then(|rest| rest.strip_suffix("\");"))
        {
            text.push_str(&read(&format!("src/{path}"))?);
        }
    }
    let (_, body) = text
        .split_once("pub enum RejectedFeature {")
        .ok_or("RejectedFeature not found")?;
    let mut variants = BTreeSet::new();
    let mut depth = 0_usize;
    for line in body.lines().map(str::trim) {
        if depth == 0 && line == "}" {
            return Ok(variants);
        }
        let name: String = line
            .chars()
            .take_while(char::is_ascii_alphanumeric)
            .collect();
        if depth == 0 && name.chars().next().is_some_and(char::is_uppercase) {
            let fresh = variants.insert(name);
            assert!(fresh, "duplicate RejectedFeature variant");
        }
        depth = depth
            .saturating_add(line.matches('{').count())
            .saturating_sub(line.matches('}').count());
    }
    Err("RejectedFeature body is not closed".into())
}

/// Whether `docs/<file>.md#<anchor>` names an existing explicit anchor.
pub(crate) fn anchor_exists(reference: &str) -> Result<bool, TestError> {
    let (file, anchor) = reference
        .split_once('#')
        .ok_or_else(|| format!("{reference}: no anchor"))?;
    let shaped = file.starts_with("docs/") && has_extension(file, "md") && !file.contains("..");
    assert!(
        shaped && !anchor.is_empty(),
        "{reference}: bad document reference"
    );
    let target = format!("<a id=\"{anchor}\"></a>");
    Ok(read(file)?.lines().any(|line| line.trim() == target))
}

/// Feature names declared in `Cargo.toml`.
pub(crate) fn cargo_features() -> Result<BTreeSet<String>, TestError> {
    let manifest: Table = read("Cargo.toml")?.parse()?;
    let features = manifest
        .get("features")
        .and_then(Value::as_table)
        .ok_or("features")?;
    Ok(features.keys().cloned().collect())
}
