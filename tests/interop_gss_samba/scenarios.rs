//! The Rust GSS initiator binds to Samba's LDAP over LDAPS with GSSAPI SASL
//! (RFC 4752) and RFC 5929 `tls-server-end-point` channel bindings.

use alloc::sync::Arc;
use core::{error::Error, time::Duration};
use std::{fs, io::Write as _, net::TcpStream};

use rskrb5_ng::{
    config::Config,
    gss::{
        self, ChannelBindings, CredStore, Credential, CredentialUsage, InitStep, InitiatorOptions,
        Name, NameType,
    },
    spnego::oid::ObjectIdentifier,
};
use rustls::{
    CertificateError, ClientConfig, ClientConnection, DigitallySignedStruct, Error as TlsError,
    RootCertStore, SignatureScheme, StreamOwned,
    client::{
        WebPkiServerVerifier,
        danger::{HandshakeSignatureValid, ServerCertVerified, ServerCertVerifier},
    },
    pki_types::{CertificateDer, ServerName, UnixTime, pem::PemObject as _},
};
use sha2::{Digest as _, Sha256};
use tokio::{runtime::Builder, time::timeout};

use crate::harness::{self, Fixture};

/// The LDAP messages of the bind.
#[path = "ldap.rs"]
mod ldap;

/// The KDC of the user domain.
const SAMBA_KDC: Fixture = Fixture::new("samba-user", "INTEROP_SAMBA_USER_KDC");

/// The LDAPS endpoint of the user domain's DC.
const SAMBA_LDAPS: Fixture = Fixture::new("samba-user", "INTEROP_SAMBA_USER_LDAPS");

/// LDAP `success`.
const SUCCESS: u32 = 0;

/// LDAP `invalidCredentials`.
const INVALID_CREDENTIALS: u32 = 49;

/// LDAP `saslBindInProgress`.
const SASL_BIND_IN_PROGRESS: u32 = 14;

/// The Windows status Samba reports for missing or wrong channel bindings.
const SEC_E_BAD_BINDINGS: &str = "80090346";

/// The DER body of the OID `sha256WithRSAEncryption`, the fixture
/// certificate's signature algorithm: RFC 5929 section 4.1 hashes it with
/// SHA-256.
const SHA256_WITH_RSA: &[u8] = &[0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x0b];

/// RFC 4752 security layer bit "no security layer".
const NO_SECURITY_LAYER: u8 = 1;

/// The channel bindings a bind sends.
#[derive(Clone, Copy, Debug)]
enum Binding {
    /// None.
    Unbound,
    /// `tls-server-end-point` of the certificate the TLS connection saw.
    ServerCertificate,
    /// `tls-server-end-point` of another certificate.
    OtherCertificate,
}

/// The verifier of Samba's autogenerated LDAPS certificate.
///
/// The certificate names the DC only in its subject common name, without the
/// subjectAltName webpki matches: the chain must verify against the per-run
/// CA, and only the name mismatch is forgiven.
#[derive(Debug)]
struct SambaCertificate(Arc<WebPkiServerVerifier>);

impl ServerCertVerifier for SambaCertificate {
    fn verify_server_cert(
        &self,
        end_entity: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        server_name: &ServerName<'_>,
        ocsp_response: &[u8],
        now: UnixTime,
    ) -> Result<ServerCertVerified, TlsError> {
        match self
            .0
            .verify_server_cert(end_entity, intermediates, server_name, ocsp_response, now)
        {
            Err(TlsError::InvalidCertificate(
                CertificateError::NotValidForName
                | CertificateError::NotValidForNameContext {
                    expected: _,
                    presented: _,
                },
            )) => Ok(ServerCertVerified::assertion()),
            verified => verified,
        }
    }

    fn verify_tls12_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, TlsError> {
        self.0.verify_tls12_signature(message, cert, dss)
    }

    fn verify_tls13_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> Result<HandshakeSignatureValid, TlsError> {
        self.0.verify_tls13_signature(message, cert, dss)
    }

    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        self.0.supported_verify_schemes()
    }
}

/// The TLS connection to the DC.
type Tls = StreamOwned<ClientConnection, TcpStream>;

/// A configuration naming the user domain's KDC.
fn config() -> Result<Config, Box<dyn Error>> {
    let realm = harness::var("INTEROP_SAMBA_USER_REALM")?;
    let domain = harness::var("INTEROP_SAMBA_USER_DNS_DOMAIN")?;
    Ok(Config::parse(&format!(
        "
[libdefaults]
 default_realm = {realm}
 dns_lookup_kdc = false
 dns_lookup_realm = false
 rdns = false
 dns_canonicalize_hostname = false

[realms]
 {realm} = {{
  kdc = {}
 }}

[domain_realm]
 .{domain} = {realm}
 {domain} = {realm}
",
        harness::var("INTEROP_SAMBA_USER_KDC")?,
    ))?)
}

/// The DC's LDAP service, `ldap@dcuser.user.rskrb5`.
fn target() -> Result<Name, Box<dyn Error>> {
    Ok(Name::import(
        format!("ldap@{}", harness::var("INTEROP_SAMBA_USER_DC")?).as_bytes(),
        NameType::HostbasedService,
    )?)
}

/// A password credential of testuser1 holding a ticket for the LDAP service.
fn credential() -> Result<Credential, Box<dyn Error>> {
    let user = format!(
        "{}@{}",
        harness::var("INTEROP_SAMBA_USER_USER")?,
        harness::var("INTEROP_SAMBA_USER_REALM")?
    );
    let name = Name::import(user.as_bytes(), NameType::Principal)?;
    let store = CredStore::new().with(
        "password",
        &harness::var("INTEROP_SAMBA_USER_USER_PASSWORD")?,
    )?;
    let mut acquired =
        Credential::acquire_cred_from(Some(&name), CredentialUsage::Initiate, &store)?;
    let (service, settings) = (target()?, config()?);
    Builder::new_current_thread()
        .enable_all()
        .build()?
        .block_on(async {
            timeout(
                Duration::from_secs(30),
                acquired.acquire_service_ticket(&service, &settings),
            )
            .await
        })??;
    Ok(acquired)
}

/// A TLS connection to the DC's LDAPS port, anchored on the per-run CA, and
/// the DER certificate it presented.
fn connect() -> Result<(Tls, Vec<u8>), Box<dyn Error>> {
    let pem = fs::read(harness::var("INTEROP_SAMBA_USER_LDAPS_CA")?)?;
    let mut roots = RootCertStore::empty();
    for anchor in CertificateDer::pem_slice_iter(&pem) {
        roots.add(anchor?)?;
    }
    let provider = Arc::new(rustls_rustcrypto::provider());
    let webpki =
        WebPkiServerVerifier::builder_with_provider(Arc::new(roots), Arc::clone(&provider))
            .build()?;
    let tls_config = ClientConfig::builder_with_provider(provider)
        .with_safe_default_protocol_versions()?
        .dangerous()
        .with_custom_certificate_verifier(Arc::new(SambaCertificate(webpki)))
        .with_no_client_auth();
    let server = ServerName::try_from(harness::var("INTEROP_SAMBA_USER_DC")?)?;
    let socket = TcpStream::connect(harness::var("INTEROP_SAMBA_USER_LDAPS")?)?;
    socket.set_read_timeout(Some(Duration::from_secs(30)))?;
    socket.set_write_timeout(Some(Duration::from_secs(30)))?;
    let mut tls = StreamOwned::new(ClientConnection::new(Arc::new(tls_config), server)?, socket);
    while tls.conn.is_handshaking() {
        let (_read, _written) = tls.conn.complete_io(&mut tls.sock)?;
    }
    let certificate = tls
        .conn
        .peer_certificates()
        .and_then(<[_]>::first)
        .ok_or("the DC presented no certificate")?
        .to_vec();
    Ok((tls, certificate))
}

/// The bindings `binding` of the certificate `certificate`.
fn bindings(
    binding: Binding,
    certificate: &[u8],
) -> Result<Option<ChannelBindings>, Box<dyn Error>> {
    assert!(
        certificate
            .windows(SHA256_WITH_RSA.len())
            .any(|window| window == SHA256_WITH_RSA),
        "the fixture certificate is signed with sha256WithRSAEncryption"
    );
    Ok(match binding {
        Binding::Unbound => None,
        Binding::ServerCertificate => Some(ChannelBindings::tls_server_end_point(
            Sha256::digest(certificate).as_slice(),
        )?),
        Binding::OtherCertificate => Some(ChannelBindings::tls_server_end_point(&[0x5a; 32])?),
    })
}

/// Send the bind request `id` carrying `credentials` and read its answer.
fn send(tls: &mut Tls, id: u8, credentials: &[u8]) -> Result<ldap::Response, Box<dyn Error>> {
    tls.write_all(&ldap::bind_request(id, credentials)?)?;
    tls.flush()?;
    ldap::read_bind_response(tls, id)
}

/// A GSSAPI SASL bind over LDAPS with `binding`: the Who Am I? identity of the
/// bound connection, or the LDAP result that refused the bind.
fn bind(binding: Binding) -> Result<Result<String, ldap::Response>, Box<dyn Error>> {
    let credential = credential()?;
    let (mut tls, certificate) = connect()?;
    let mut options = InitiatorOptions::new();
    if let Some(sent) = bindings(binding, &certificate)? {
        options = options.with_channel_bindings(sent);
    }
    let mut initiator = gss::Initiator::new(target()?, options);
    let InitStep::Continue(request_token) = initiator.init_sec_context(&credential, None)? else {
        return Err("mutual authentication waits for the AP-REP".into());
    };
    let first = send(&mut tls, 1, &request_token)?;
    if first.code() != SASL_BIND_IN_PROGRESS {
        return Ok(Err(first));
    }
    let reply_token = first.payload().ok_or("the DC sent no AP-REP")?;
    let InitStep::Complete(None) = initiator.init_sec_context(&credential, Some(reply_token))?
    else {
        return Err("the AP-REP completes the initiator".into());
    };
    let mut context = initiator.into_established()?;
    harness::assert_negotiated_mechanism(
        ObjectIdentifier::krb5().arcs(),
        context.inquire().mechanism().arcs(),
    )?;
    let offer = send(&mut tls, 2, &[])?;
    if offer.code() != SASL_BIND_IN_PROGRESS {
        return Ok(Err(offer));
    }
    let layers = context.unwrap(offer.payload().ok_or("the DC offered no layers")?)?;
    let (&offered, max_size) = layers
        .message()
        .split_first()
        .ok_or("an empty layer offer")?;
    assert_eq!(max_size.len(), 3, "RFC 4752 offers a 24-bit size");
    assert_ne!(
        offered & NO_SECURITY_LAYER,
        0,
        "Samba offers no security layer over TLS"
    );
    let choice = context.wrap(&[NO_SECURITY_LAYER, 0, 0, 0], false)?;
    let done = send(&mut tls, 3, &choice)?;
    if done.code() != SUCCESS {
        return Ok(Err(done));
    }
    tls.write_all(&ldap::whoami_request(4)?)?;
    tls.flush()?;
    let whoami = ldap::read_extended_response(&mut tls, 4)?;
    assert_eq!(whoami.code(), SUCCESS, "Who Am I? answers: {whoami:?}");
    Ok(Ok(String::from_utf8(
        whoami.payload().unwrap_or_default().to_vec(),
    )?))
}

/// Asserts that Samba refused the bind for its channel bindings.
fn assert_bad_bindings(outcome: Result<String, ldap::Response>) -> Result<(), Box<dyn Error>> {
    let refused = outcome
        .err()
        .ok_or("Samba accepted a bind without the TLS channel bindings")?;
    assert_eq!(refused.code(), INVALID_CREDENTIALS, "{refused:?}");
    assert!(
        refused.diagnostic().contains(SEC_E_BAD_BINDINGS),
        "Samba names SEC_E_BAD_BINDINGS: {refused:?}"
    );
    Ok(())
}

/// A bind carrying the `tls-server-end-point` bindings of the certificate the
/// TLS connection saw is accepted, and the connection is testuser1's.
#[test]
fn a_bound_gssapi_bind_over_ldaps_is_accepted() -> Result<(), Box<dyn Error>> {
    if !harness::require(
        "a_bound_gssapi_bind_over_ldaps_is_accepted",
        &[SAMBA_KDC, SAMBA_LDAPS],
    )? {
        return Ok(());
    }
    let identity = bind(Binding::ServerCertificate)?
        .map_err(|refused| format!("Samba refused the bound bind: {refused:?}"))?;
    assert_eq!(
        identity,
        format!(
            "u:{}\\{}",
            harness::var("INTEROP_SAMBA_USER_NETBIOS")?,
            harness::var("INTEROP_SAMBA_USER_USER")?
        ),
        "the bound connection is testuser1's"
    );
    Ok(())
}

/// A bind without channel bindings is refused with `SEC_E_BAD_BINDINGS`.
#[test]
fn an_unbound_gssapi_bind_over_ldaps_is_refused() -> Result<(), Box<dyn Error>> {
    if !harness::require(
        "an_unbound_gssapi_bind_over_ldaps_is_refused",
        &[SAMBA_KDC, SAMBA_LDAPS],
    )? {
        return Ok(());
    }
    assert_bad_bindings(bind(Binding::Unbound)?)
}

/// A bind carrying the bindings of another certificate is refused with
/// `SEC_E_BAD_BINDINGS`.
#[test]
fn a_bind_with_another_certificates_bindings_is_refused() -> Result<(), Box<dyn Error>> {
    if !harness::require(
        "a_bind_with_another_certificates_bindings_is_refused",
        &[SAMBA_KDC, SAMBA_LDAPS],
    )? {
        return Ok(());
    }
    assert_bad_bindings(bind(Binding::OtherCertificate)?)
}
